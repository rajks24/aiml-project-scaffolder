def _precommit(o: ProjectOptions) -> str:
    prefix = "uv run " if o.environment_manager == "uv" else "python -m "
    return f"""repos:
  - repo: local
    hooks:
      - id: ruff-check
        name: ruff check
        entry: {prefix}ruff check --fix
        language: system
        types: [python]
      - id: ruff-format
        name: ruff format
        entry: {prefix}ruff format
        language: system
        types: [python]
"""


def _uv_ci_job(o: ProjectOptions, name: str) -> str:
    return f"""  {name}:
    runs-on: ubuntu-latest
    steps:
      - uses: actions/checkout@df4cb1c069e1874edd31b4311f1884172cec0e10 # v6
        with:
          persist-credentials: false
      - uses: astral-sh/setup-uv@08807647e7069bb48b6ef5acd8ec9567f424441b # v8.1.0
        with:
          enable-cache: true
      - run: uv python install {o.python_version}
      - run: uv sync --locked {_uv_extra_flags(o)} --group notebooks
      - run: uv run ruff check .
      - run: uv run ruff format --check .
      - run: uv run pytest --cov={o.package_name} --cov-report=term-missing
"""


def _conda_ci_job(o: ProjectOptions, name: str) -> str:
    return f"""  {name}:
    runs-on: ubuntu-latest
    defaults:
      run:
        shell: bash -el {{0}}
    steps:
      - uses: actions/checkout@df4cb1c069e1874edd31b4311f1884172cec0e10 # v6
        with:
          persist-credentials: false
      - uses: conda-incubator/setup-miniconda@8ee1f361103df19b6f8c8655fd3967a8ecb162d5 # v4
        with:
          activate-environment: {o.project_name}
          environment-file: environment.yml
      - run: ruff check .
      - run: ruff format --check .
      - run: pytest --cov={o.package_name} --cov-report=term-missing
"""


def _ci(o: ProjectOptions) -> str:
    header = "name: CI\n\non:\n  push:\n  pull_request:\n\njobs:\n"
    if o.environment_manager == "uv":
        return header + _uv_ci_job(o, "quality")
    if o.environment_manager == "conda":
        return header + _conda_ci_job(o, "quality")
    return header + _uv_ci_job(o, "uv-quality") + _conda_ci_job(o, "conda-quality")


