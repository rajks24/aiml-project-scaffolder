from .catalog import DEPENDENCIES
from .models import ProjectOptions


def _quoted(items: list[str]) -> str:
    return "\n".join(f'    "{item}",' for item in items)


def _uv_extra_flags(o: ProjectOptions) -> str:
    return " ".join(f"--extra {profile}" for profile in o.profiles)


def _optional_dependencies() -> str:
    return "\n".join(
        f"{profile} = [\n{_quoted(list(packages))}\n]"
        for profile, packages in DEPENDENCIES.profiles.items()
    )


def _pyproject(o: ProjectOptions) -> str:
    dependencies = [
        *DEPENDENCIES.core,
        *DEPENDENCIES.tracking[o.tracking],
    ]
    dev = [*DEPENDENCIES.groups["dev"], *DEPENDENCIES.data_versioning[o.data_versioning]]
    return f'''[build-system]
requires = ["hatchling>=1.27"]
build-backend = "hatchling.build"

[project]
name = "{o.project_name}"
version = "0.1.0"
description = {json.dumps(o.title)}
readme = "README.md"
requires-python = ">={o.python_version}"
dependencies = [
{_quoted(dependencies)}
]

[project.optional-dependencies]
{_optional_dependencies()}

[project.scripts]
experiment = "{o.package_name}.cli:main"

[dependency-groups]
dev = [
{_quoted(dev)}
]
notebooks = [
{_quoted(list(DEPENDENCIES.groups["notebooks"]))}
]

[tool.hatch.build.targets.wheel]
packages = ["src/{o.package_name}"]

[tool.ruff]
line-length = 100
target-version = "py{o.python_version.replace(".", "")}"

[tool.ruff.lint]
select = ["E", "F", "I", "B", "UP", "SIM"]
ignore = ["UP037"]

[tool.pytest.ini_options]
addopts = "-q --strict-markers"
testpaths = ["tests"]
'''


def _environment_yml(o: ProjectOptions) -> str:
    pip_packages = [
        *DEPENDENCIES.groups["dev"],
        *DEPENDENCIES.groups["notebooks"],
        *DEPENDENCIES.data_versioning[o.data_versioning],
    ]
    pip_lines = "\n".join(f"      - {json.dumps(package)}" for package in pip_packages)
    return f"""name: {o.project_name}
channels:
  - conda-forge
dependencies:
  - python={o.python_version}
  - pip
  - pip:
      # Editable install reads runtime dependencies from pyproject.toml.
      - "-e .[{",".join(o.profiles)}]"
{pip_lines}
"""


def _setup_guide(o: ProjectOptions) -> str:
    uv = f"""### uv

```bash
uv sync {_uv_extra_flags(o)} --group notebooks
uv run experiment --config configs/experiment.toml
uv run pytest
uv run ruff check .
uv run python -m ipykernel install --user --name {o.project_name}-uv \\
  --display-name "Python ({o.title} - uv)"
uv run jupyter lab
```"""
    conda = f"""### Conda

```bash
conda env create --file environment.yml
conda activate {o.project_name}
experiment --config configs/experiment.toml
pytest
ruff check .
python -m ipykernel install --user --name {o.project_name}-conda \\
  --display-name "Python ({o.title} - Conda)"
jupyter lab
```"""
    if o.environment_manager == "uv":
        return "Install [uv](https://docs.astral.sh/uv/) and run:\n\n" + uv
    if o.environment_manager == "conda":
        return "Install Conda or Miniforge and run:\n\n" + conda
    return (
        "Choose one isolated environment for each working session; do not activate Conda and "
        "`.venv` together. Both paths install the same project dependencies.\n\n"
        + uv
        + "\n\n"
        + conda
    )


def _readme(o: ProjectOptions) -> str:
    integration = []
    if o.tracking == "mlflow":
        mlflow_command = "uv run mlflow ui" if o.environment_manager == "uv" else "mlflow ui"
        integration.append(
            f"- MLflow records parameters, metrics, and run artifacts (`{mlflow_command}`)."
        )
    else:
        integration.append("- Runs are recorded locally under `artifacts/runs/` as portable JSON.")
    if o.data_versioning == "dvc":
        integration.append(
            "- DVC versions large data/models. Git tracks `.dvc/config`, `.dvcignore`, `*.dvc`, "
            "`dvc.yaml`, and `dvc.lock`; only DVC's local cache, temp state, and local config are "
            "ignored."
        )
    return f"""# {o.title}

Reproducible experiment project with **{", ".join(o.profiles)}** profiles, generated by AIML
Project Scaffolder.

## Start here

{_setup_guide(o)}

## Composable profiles

This project declares every profile as a standard Python optional dependency. The generated setup
commands install the selected profiles: `{", ".join(o.profiles)}`. You can change the combination
later without regenerating the project.

| Project type | Recommended profiles |
|---|---|
| Classical ML | `general` |
| Tabular ML | `general` + `tabular` |
| Image/deep learning | `deep-learning` |
| Deep learning with preprocessing/metrics | `general` + `deep-learning` |
| Basic OpenAI/LLM application | `genai` |
| GenAI with CSV/data analysis | `general` + `genai` |
| Hugging Face dataset/evaluation workflow | `general` + `genai` + `hf` |
| RAG with embeddings/clustering/evaluation | `general` + `genai` |

Examples:

```bash
uv sync --extra general
uv sync --extra general --extra deep-learning
uv sync --extra general --extra genai
uv sync --extra general --extra genai --extra hf
```

For Conda, update the `profiles` selection in `configs/experiment.toml`, change the editable extra
list in `environment.yml`, then run `conda env update --file environment.yml --prune`.

## Experiment loop

1. Register the source and license in `DATA_SOURCES.md`; never modify `data/raw/` in place.
2. Put reusable logic in `src/{o.package_name}/`, not only in notebooks.
3. Copy `configs/experiment.toml`, change one hypothesis at a time, and run it.
4. Compare the manifests in `artifacts/runs/` (or the configured tracker).
5. Add tests for transformations and leakage-sensitive feature logic before scaling a run.

{chr(10).join(integration)}

## Layout

```text
configs/                 versioned experiment parameters
data/{{raw,interim,processed}}  local data stages
notebooks/               exploration only
src/{o.package_name}/    tested package and experiment runner
tests/                   fast automated checks
artifacts/runs/           generated run manifests (Git-ignored)
models/                  generated model artifacts (Git-ignored)
reports/figures/         publication-ready figures
```

## Configuration and secrets

Commit configuration, but never credentials. Copy `.env.example` to `.env` for local secrets.
The starter reads TOML with Python's standard library and records the config plus environment
metadata with every run. Replace `objective()` in `experiment.py` with the smallest testable
implementation of your hypothesis.

## Reproducibility checklist

- Commit dependency specifications/locks, configuration, code, data metadata/checksums, and seed.
- Fit preprocessing only on training folds; use pipelines to prevent leakage.
- Keep a final untouched test set and report uncertainty, not only a best score.
- Record model/data/license constraints and validate on slices that matter to users.
- For GenAI, version prompts and evaluation sets and record provider/model identifiers.

## Author

{o.author}
"""


def _experiment(o: ProjectOptions) -> str:
    mlflow_import = "import mlflow\n\n" if o.tracking == "mlflow" else ""
    mlflow_start = textwrap.dedent(
        """
        mlflow.set_experiment(config.project.name)
        with mlflow.start_run(run_name=run_id):
            mlflow.log_params({"seed": config.experiment.seed, "profiles": config.project.profile})
            mlflow.log_metrics(metrics)
            mlflow.log_artifact(str(manifest_path))
        """
    ).strip()
    tracking = textwrap.indent(mlflow_start, "    ") if o.tracking == "mlflow" else ""
    return f'''"""A minimal reproducible run. Replace objective() with your hypothesis."""

from __future__ import annotations

import json
import platform
import random
import subprocess
from dataclasses import asdict
from datetime import UTC, datetime
from pathlib import Path

{mlflow_import}from .config import AppConfig


def _git_revision() -> str | None:
    try:
        return subprocess.check_output(
            ["git", "rev-parse", "HEAD"], text=True, stderr=subprocess.DEVNULL
        ).strip()
    except (FileNotFoundError, subprocess.CalledProcessError):
        return None


def objective(seed: int) -> dict[str, float]:
    """Deterministic smoke objective; replace with real training or evaluation."""
    rng = random.Random(seed)
    return {{"example_score": rng.random()}}


def run(config: AppConfig) -> Path:
    started = datetime.now(UTC)
    run_id = started.strftime("%Y%m%dT%H%M%S%fZ")
    metrics = objective(config.experiment.seed)
    manifest = {{
        "run_id": run_id,
        "started_at": started.isoformat(),
        "git_revision": _git_revision(),
        "python": platform.python_version(),
        "config": asdict(config),
        "metrics": metrics,
    }}
    output_dir = Path(config.output.directory) / run_id
    output_dir.mkdir(parents=True, exist_ok=False)
    manifest_path = output_dir / "manifest.json"
    manifest_path.write_text(json.dumps(manifest, indent=2) + "\\n", encoding="utf-8")
{tracking}
    return manifest_path
'''


